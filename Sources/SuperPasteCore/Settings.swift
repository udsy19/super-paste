/// Which end of the Paste Stack ⌘V takes from (behaviour.md §3.6).
public enum StackDirection: String, Codable, CaseIterable, Sendable {
    case top, bottom
}

/// The default capture filters (behaviour.md §2.3).
public enum CaptureDefaults {
    /// Password managers. An entry matches a bundle id exactly or as a dotted prefix ("com.1password" matches
    /// "com.1password.1password"); an entry that starts with "." matches as a suffix (".nordpass").
    public static let ignoredApps = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password", "com.agilebits.onepassword-osx",
        "com.agilebits.onepassword4", "com.agilebits.onepassword7", "com.lastpass.LastPass", "com.dashlane.Dashlane",
        "com.bitwarden.desktop", "in.sinew.Enpass-Desktop", "com.SiberSystems.RoboForm", "com.callpod.keepermac",
        "com.keepersecurity", ".nordpass",
    ]

    /// What "Ignore confidential content" adds to or removes from `ignoredPasteboardTypes`.
    public static let confidentialTypes = [PasteboardType.concealed]
    /// What "Ignore transient content" adds to or removes from `ignoredPasteboardTypes`.
    public static let transientTypes = [
        PasteboardType.transient, PasteboardType.autoGenerated, "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping", "Pasteboard generator type",
    ]
    /// A copy whose pasteboard carries any of these types is not captured.
    public static let ignoredTypes = [
        PasteboardType.transient, PasteboardType.autoGenerated, PasteboardType.concealed,
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ]
}

/// Pause choices in the Pause menu, in seconds (behaviour.md §6.3); "Until I Resume" pauses without an end.
