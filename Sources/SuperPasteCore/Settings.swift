public extension Defaults {
    /// "Ignore confidential content": whether `ignoredPasteboardTypes` holds every confidential type.
    static var ignoresConfidentialContent: Bool {
        get { Set(Defaults[.ignoredPasteboardTypes]).isSuperset(of: CaptureDefaults.confidentialTypes) }
        set { setIgnored(CaptureDefaults.confidentialTypes, newValue) }
    }

    /// "Ignore transient content": whether `ignoredPasteboardTypes` holds every transient type.
    static var ignoresTransientContent: Bool {
        get { Set(Defaults[.ignoredPasteboardTypes]).isSuperset(of: CaptureDefaults.transientTypes) }
        set { setIgnored(CaptureDefaults.transientTypes, newValue) }
    }

    private static func setIgnored(_ types: [String], _ ignored: Bool) {
        var list = Defaults[.ignoredPasteboardTypes].filter { !types.contains($0) }
        if ignored { list += types }
        Defaults[.ignoredPasteboardTypes] = list
    }
}
