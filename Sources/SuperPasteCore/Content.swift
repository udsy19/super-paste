// Pure content rules every module agrees on: pasteboard type names, the payload checksum, text classification and
// the identity of this Mac.

/// Pasteboard type names with a fixed meaning (behaviour.md §2.3, §2.4, §3.5).
public enum PasteboardType {
    /// Added to everything Super Paste writes, carrying the item id, so the monitor sees a restore instead of a copy.
    public static let itemID = "org.superpaste.item-id"
    /// nspasteboard.org: the bundle id of the app that wrote the pasteboard. Super Paste stamps its own on writes.
    public static let source = "org.nspasteboard.source"
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Present when the content arrived by Universal Clipboard from another Apple device.
    public static let remoteClipboard = "com.apple.is-remote-clipboard"
    public static let plainText = "public.utf8-plain-text"
    public static let urlName = "public.url-name"

    /// Dropped from stored and written items whatever the app (OLE plumbing that breaks pasting elsewhere).
    public static let banned: Set<String> = [
        "com.microsoft.ole.source", "com.microsoft.ObjectLink", "com.microsoft.Link-Source", "com.microsoft.DataObject",
    ]

    /// Markers that say nothing about the content: left out of the checksum, so the same text copied in two apps,
    /// or restored by Super Paste, dedupes.
    public static let volatile: Set<String> = [itemID, source, remoteClipboard]
}

/// SHA-256 helpers for payload identity and content-addressed blobs.
public enum ClipChecksum {
    /// The checksum of a payload: entries in order; within an entry, representations sorted by type, `volatile`
    /// types skipped. Lowercase hex.
    public static func of(_ entries: [EntryData]) -> String {
        var hasher = SHA256()
        for entry in entries {
            hasher.update(data: Data("entry\0".utf8))
            for rep in entry.reps.sorted(by: { $0.type < $1.type }) where !PasteboardType.volatile.contains(rep.type) {
                hasher.update(data: Data(rep.type.utf8))
                var length = UInt64(rep.data.count).bigEndian
                hasher.update(data: Data([0]) + Data(bytes: &length, count: 8))
                hasher.update(data: rep.data)
            }
        }
        return hex(hasher.finalize())
    }

    /// Lowercase hex SHA-256 of `data` (blob digests).
    public static func hex(of data: Data) -> String { hex(SHA256.hash(data: data)) }

    private static func hex(_ digest: SHA256.Digest) -> String { digest.map { String(format: "%02x", $0) }.joined() }
}

/// Classifying plain text (behaviour.md §2.5): shared by capture, New Text Item, editing and MCP `create_item`.
public enum TextClassifier {
    /// `.color` for a hex colour, `.link` for a single web URL, otherwise `.text`.
    public static func kind(of text: String) -> ItemKind {
        if colorHex(in: text) != nil { return .color }
        if linkURL(in: text) != nil { return .link }
        return .text
    }

    /// "#RRGGBB" (upper case) when the whole text, trimmed, is `#?[0-9A-Fa-f]{6}`.
    public static func colorHex(in text: String) -> String? {
        var t = Substring(text.trimmingCharacters(in: .whitespacesAndNewlines))
        if t.first == "#" { t = t.dropFirst() }
        guard t.count == 6, t.allSatisfy(\.isHexDigit) else { return nil }
        return "#" + t.uppercased()
    }

    /// The URL when the whole text, trimmed, is one http(s) URL or a "www." address (which gets https://).
    public static func linkURL(in text: String) -> URL? {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty, !t.contains(where: \.isWhitespace) else { return nil }
        let lower = t.lowercased()
        let candidate: String
        if lower.hasPrefix("http://") || lower.hasPrefix("https://") {
            candidate = t
        } else if lower.hasPrefix("www.") {
            candidate = "https://" + t
        } else {
            return nil
        }
        guard let url = URL(string: candidate), let host = url.host, host.contains(".") || host == "localhost"
        else { return nil }
        return url
    }
}

public extension Device {
    /// This Mac: id is a SHA-256 of the hardware UUID (so the raw identifier never leaves the Mac), name is the
    /// computer name from Sharing settings.
    static let current: Device = {
        let service = IOServiceGetMatchingService(kIOMainPortDefault, IOServiceMatching("IOPlatformExpertDevice"))
        defer { IOObjectRelease(service) }
        let hardware = IORegistryEntryCreateCFProperty(service, kIOPlatformUUIDKey as CFString, kCFAllocatorDefault, 0)?
            .takeRetainedValue() as? String ?? "unknown-mac"
        let id = String(ClipChecksum.hex(of: Data("superpaste-device:\(hardware)".utf8)).prefix(32))
        let name = SCDynamicStoreCopyComputerName(nil, nil) as String? ?? "Mac"
        let version = Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String
        return Device(id: id, name: name, family: .mac, appVersion: version)
    }()
}
